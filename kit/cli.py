"""Two developer commands that work on any flow under flows/.

    python -m kit.cli graph <flow>              draw the flow's graph, offline -> flows/<flow>/GRAPH.md
    python -m kit.cli run <flow> [--case ID]    run one eval case through the flow (live API)

Both rely only on conventions every flow already follows: flows/<flow>/evals.py defines DATASET and
flow(case), and flows/<flow>/graph.py compiles its StateGraph with name="<flow>". A flow can add
GATES = {"<node>": "<who or what must say yes>"} to graph.py; those nodes are drawn as gates. It
can also add ROUTES = {("<from>", "<to>"): "<condition>"} to label its routing edges.

`graph` builds the graph exactly the way a real run does, then stops at compile time, before the
first model call. Any model call before that point raises instead of reaching the API.

`run` executes what the eval executes for that case, scripted approval decisions included, and
prints the outcome next to what the case expects. The trace is structural only (content="none").
The outcome goes to the console, which the coding assistant's transcript records: synthetic cases
only.
"""

from __future__ import annotations

import argparse
import importlib
import json
import sys
from pathlib import Path
from unittest import mock

from langgraph.graph import StateGraph

from evals.harness import load_cases
from kit import llm, tracing

ROOT = Path(__file__).resolve().parents[1]


class _Captured(BaseException):  # BaseException: a flow's `except Exception` can't swallow it
    def __init__(self, graph):
        self.graph = graph


def _refuse_model(*_args, **_kwargs):
    raise RuntimeError("drawing a graph must not call the model: this flow calls it before compiling")


def capture_graph(flow: str):
    """The flow's compiled graph, built as a real run builds it, with no model call."""
    evals = importlib.import_module(f"flows.{flow}.evals")
    case = load_cases(evals.DATASET)[0]
    original = StateGraph.compile

    def spy(self, *args, **kwargs):
        compiled = original(self, *args, **kwargs)
        if kwargs.get("name") == flow:
            raise _Captured(compiled)
        return compiled

    with mock.patch.object(StateGraph, "compile", spy), llm.fake(_refuse_model):
        try:
            evals.flow(case)
        except _Captured as c:
            return c.graph
    raise RuntimeError(f"flows/{flow} never compiled a graph named {flow!r}")


# Every class sets its own text colour: the dark theme's default light text is unreadable on light
# fills, which is how LangGraph's own draw_mermaid() renders in a dark VS Code preview.
_CLASSES = {
    "step": "fill:#e0e7ff,stroke:#4f46e5,color:#111827",
    "gate": "fill:#fde68a,stroke:#b45309,stroke-width:3px,color:#111827",
    "terminal": "fill:#e5e7eb,stroke:#6b7280,color:#111827",
}
_SHAPES = {"step": ('("', '")'), "gate": ('{{"', '"}}'), "terminal": ('(["', '"])')}
_TERMINALS = {"__start__": "start", "__end__": "end"}


def _flow_tables(flow: str) -> tuple[dict, dict]:
    module = importlib.import_module(f"flows.{flow}.graph")
    return getattr(module, "GATES", {}), getattr(module, "ROUTES", {})


def mermaid(flow: str) -> str:
    """Mermaid for the flow's compiled graph: gates as hexagons, routing edges dotted and labelled.

    Drawn from the graph's own nodes and edges rather than draw_mermaid(), so the shapes, labels
    and colours can be controlled. Labels come from graph.py's optional ROUTES
    {("<from>", "<to>"): "<condition>"}; the graph itself doesn't record why an edge is taken.
    """
    graph = capture_graph(flow).get_graph()
    gates, routes = _flow_tables(flow)
    lines = ["flowchart TD"]
    for node in graph.nodes:
        kind = "terminal" if node in _TERMINALS else "gate" if node in gates else "step"
        label = _TERMINALS.get(node, node.replace("_", " "))
        opened, closed = _SHAPES[kind]
        lines.append(f"    {node}{opened}{label}{closed}:::{kind}")
    for e in graph.edges:
        arrow = "-.->" if e.conditional else "-->"
        label = routes.get((e.source, e.target))
        lines.append(f"    {e.source} {arrow}{f'|{label}|' if label else ''} {e.target}")
    lines += [f"    classDef {name} {style}" for name, style in _CLASSES.items()]
    return "\n".join(lines)


def write_graph_md(flow: str) -> Path:
    gates, _ = _flow_tables(flow)
    lines = [
        f"# {flow} — graph",
        "",
        f"Generated by `make graph FLOW={flow}` from the compiled LangGraph graph, so it matches the",
        "code. Yellow hexagons are gates, where a code check or a person must say yes. Dotted arrows",
        "are routing decisions, labelled with the condition; solid arrows always run.",
        "",
        "```mermaid",
        mermaid(flow),
        "```",
    ]
    if gates:
        lines += ["", "## Gates (highlighted)", "", "| node | what must say yes |", "|---|---|"]
        lines += [f"| `{node}` | {why} |" for node, why in gates.items()]
    path = ROOT / "flows" / flow / "GRAPH.md"
    path.write_text("\n".join(lines) + "\n")
    return path


def run_case(flow: str, case_id: str | None) -> dict:
    evals = importlib.import_module(f"flows.{flow}.evals")
    cases = load_cases(evals.DATASET)
    case = next((c for c in cases if c.id == case_id), None) if case_id else cases[0]
    if case is None:
        ids = ", ".join(c.id for c in cases)
        raise SystemExit(f"no case {case_id!r} in {evals.DATASET.name}; ids: {ids}")
    with tracing.run(f"{flow}-run", content="none") as run_dir:
        output = evals.flow(case)
    return {
        "case": case.id,
        "category": case.category,
        "expect": case.expect,
        "output": output,
        "trace": str(run_dir),
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m kit.cli")
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("graph", help="draw a flow's graph (offline) to flows/<flow>/GRAPH.md")
    g.add_argument("flow")
    r = sub.add_parser("run", help="run one eval case through a flow (live API)")
    r.add_argument("flow")
    r.add_argument("--case", default=None, help="case id (default: the first case)")
    args = ap.parse_args(argv)

    if args.cmd == "graph":
        path = write_graph_md(args.flow)
        print(mermaid(args.flow))
        print(f"\nwrote {path.relative_to(ROOT)} (open it and press Ctrl+Shift+V for the drawing)")
    else:
        print(json.dumps(run_case(args.flow, args.case), indent=2, default=str))
    return 0


if __name__ == "__main__":
    sys.exit(main())
